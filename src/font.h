// clang-format on

// --font large. Drawn at its own size with sharp pixels, which is what a 1.5x scale of the
// 5x8 font cannot be: nearest-neighbour gives it strokes of uneven width, and filtering
// blurs it.
inline void UseLarge(bool on) {
  g_large = on;
  kGlyphW = on ? 7 : 5;
  kGlyphH = on ? 13 : 8;
  kAdvance = on ? 7 : 6;
  kLineH = on ? 15 : 10;
}

