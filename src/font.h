// A 5x7 bitmap font, drawn into the software framebuffer.
//
// The HUD is painted into the SAME Image the world is painted into, one pixel at a
// time, rather than with GDI's TextOut onto the window DC. That is a deliberate choice
// and it is the same one that made the renderer software in the first place: because
// the program owns every pixel it draws, `--snapshot --hud` produces a PNG of exactly
// what the window shows, with no window and no graphics context. The overlay is
// therefore checkable without a person looking at a desktop -- and the glyphs below
// were in fact proof-read that way, with `--font-sample`, not by eye on screen.
//
// The alternative, TextOut into a memory DC, would have worked and cost no font table.
// It was passed over because it splits the frame into "pixels we own" and "pixels
// Windows drew", and the second kind cannot be inspected offline.
//
// 95 glyphs, ASCII 32..126. Each is 5x8: rows 0..6 are the cap-height box and row 7 is
// the descender, so p q g y j and the comma hang below the baseline while their bowls
// stay at x-height with a c e. The first cut was 5x7 with no descender row, which
// pulled those bowls up to cap height -- the composed HUD read "sPace Play" and "esc
// Quit", which is exactly the kind of error --font-sample exists to catch.
// Advance is 6 px and line height 10 px.

