inline int Advance() { return kAdvance; }

inline int MeasureWidth(const char* s, int scale = 1) {
  const int n = static_cast<int>(strlen(s));
  if (n == 0) return 0;
  return (n * kAdvance - 1) * scale;
}

inline int LineHeight(int scale = 1) { return kLineH * scale; }

// Draws `s` with its top-left at (x, y). No wrapping and no newline handling: the HUD
// composes its own lines, which keeps this function a single loop.
inline void DrawString(Image* img, int x, int y, const char* s, Rgb fg, int scale = 1) {
  for (const char* p = s; *p; ++p) {
    const uint8_t* rows = Glyph(*p);
    for (int gy = 0; gy < kGlyphH; ++gy) {
      const uint8_t bits = rows[gy];
      for (int gx = 0; gx < kGlyphW; ++gx) {
        if (!(bits & (1u << (kGlyphW - 1 - gx)))) continue;
        for (int sy = 0; sy < scale; ++sy)
          for (int sx = 0; sx < scale; ++sx)
            img->Set(x + gx * scale + sx, y + gy * scale + sy, fg);
      }
    }
    x += kAdvance * scale;
  }
}

// Same, over a filled panel. `pad` is in pixels and applies on every side.
inline void DrawStringBoxed(Image* img, int x, int y, const char* s, Rgb fg, Rgb bg,
                            int pad = 2, int scale = 1) {
  img->FillRect(x - pad, y - pad, MeasureWidth(s, scale) + 2 * pad,
                kGlyphH * scale + 2 * pad, bg);
  DrawString(img, x, y, s, fg, scale);
}

